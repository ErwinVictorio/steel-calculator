import { test, expect } from '@playwright/test'

test('direct formulas, quantity validation and reset', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('Thickness', { exact: true }).fill('6')
  await page.getByLabel('Width', { exact: true }).fill('4')
  await page.getByLabel('Length', { exact: true }).fill('8')
  await page.getByLabel('Quantity', { exact: true }).fill('3')
  await expect(page.locator('.weight-value')).toHaveText('420.08 kg')
  await expect(page.getByRole('combobox')).toHaveCount(0)
  await page.getByLabel('Thickness', { exact: true }).fill('5.5')
  await page.getByLabel('Length', { exact: true }).fill('12')
  await page.getByLabel('Quantity', { exact: true }).fill('1')
  await expect(page.locator('.weight-value')).toHaveText('192.54 kg')
  await expect(page.getByLabel('Item Name', { exact: true })).toHaveValue('MS PLATE 5.5MM X 4FT X 12FT')
  await page.evaluate(() => {
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.copiedItemName = text } } })
  })
  await page.getByRole('button', { name: 'Copy', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Copied!')
  expect(await page.evaluate(() => window.copiedItemName)).toBe('MS PLATE 5.5MM X 4FT X 12FT')
  await page.evaluate(() => {
    navigator.clipboard.writeText = async () => { throw new Error('Permission denied') }
  })
  await page.getByRole('button', { name: 'Copy', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('copy it manually')
  await page.getByLabel('Quantity', { exact: true }).fill('1.5')
  await expect(page.locator('.weight-value')).toHaveText('— kg')
  await expect(page.getByText('Enter a whole number of pieces.')).toBeVisible()
  await page.getByRole('button', { name: /Reset/ }).click()
  await expect(page.getByLabel('Thickness', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Item Name', { exact: true })).toHaveValue('')
  await expect(page.getByRole('button', { name: 'Copy', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: /Checkered Plate/ }).click()
  await expect(page.locator('.weight-value')).toHaveText('— kg')
  await page.getByLabel('Thickness', { exact: true }).fill('6')
  await page.getByLabel('Width', { exact: true }).fill('4')
  await page.getByLabel('Length', { exact: true }).fill('8')
  await page.getByLabel('Quantity', { exact: true }).fill('3')
  await expect(page.locator('.weight-value')).toHaveText('435.08 kg')
  await expect(page.getByLabel('Item Name', { exact: true })).toHaveValue('CHECKERED PLATE 6MM X 4FT X 8FT')
  await page.getByRole('button', { name: /Beams/ }).click()
  await page.getByLabel('LBS').fill('22')
  await expect(page.locator('.weight-value')).toHaveText('200.00 kg')
  await page.getByLabel('Beam length').selectOption('12')
  await expect(page.locator('.weight-value')).toHaveText('400.00 kg')
  await expect(page.getByLabel('Item Name', { exact: true })).toHaveValue('BEAMS 22LBS/FT X 12M')
  await page.getByRole('button', { name: /Flat Bar/ }).click()
  await page.getByLabel('Thickness', { exact: true }).fill('6')
  await page.getByLabel('Width', { exact: true }).fill('2')
  await page.getByLabel('Length', { exact: true }).fill('6')
  await expect(page.locator('.weight-value')).toHaveText('4.38 kg')
  await expect(page.getByLabel('Item Name', { exact: true })).toHaveValue('FLAT BAR 6MM X 2IN X 6FT')
  await expect(page.getByRole('combobox')).toHaveCount(0)
  expect(errors).toEqual([])
})

for (const width of [360, 768, 1440]) {
  test(`layout fits viewport at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('/')
    await expect(page.getByRole('heading', { name: 'Steel Weight Calculator.' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/calculator-${width}.png`, fullPage: true })
  })
}
